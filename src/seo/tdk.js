const canonicalUrl = (path) => new URL(path, siteConfig.url).toString();

function getSocialMetadata(entry, canonical, type) {
  const url = canonicalUrl(canonical);
  return {
    alternates: { canonical: url },
    openGraph: {
      type,
      url,
      siteName: siteConfig.name,
      title: entry.title,
      description: entry.description,
      images: [{ url: siteConfig.ogImage, width: 1730, height: 909, alt: "Mortal Shell II Wiki — Guides, Builds, and Map" }],
    },
    twitter: {
      card: "summary_large_image",
      title: entry.title,
      description: entry.description,
      images: [siteConfig.ogImage],
    },
  };
}

export function getPageMetadata(key, canonical) {
  const entry = pageTdk[key];
  return { title: entry.title, description: entry.description, keywords: entry.keywords, robots: { index: true, follow: true }, ...getSocialMetadata(entry, canonical, "website") };
}

export function getRecordMetadata(seo, canonical) {
  return { title: seo.title, description: seo.description, keywords: seo.keywords, robots: { index: true, follow: true }, ...getSocialMetadata(seo, canonical, "article") };
}
